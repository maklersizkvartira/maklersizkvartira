const STORAGE_KEY = 'maklersiz.admin.language';

export const state = {
  language: (() => {
    try {
      const stored = localStorage.getItem(STORAGE_KEY);
      if (stored && DICTIONARIES[stored]) return stored;
    } catch (error) {
      /* storage unavailable */
    }
    return 'uz';
  })(),
};

export function setLanguage(language) {
  if (!DICTIONARIES[language]) return;
  state.language = language;
  try {
    localStorage.setItem(STORAGE_KEY, language);
  } catch (error) {
    /* ignore */
  }
  document.documentElement.lang = language;
}

function resolve(dictionary, path) {
  return path
    .split('.')
    .reduce((node, key) => (node && typeof node === 'object' ? node[key] : undefined), dictionary);
}

export function t(key, params) {
  let value = resolve(DICTIONARIES[state.language], key);
  if (typeof value !== 'string') value = resolve(DICTIONARIES.uz, key);
  if (typeof value !== 'string') return key;
  if (!params) return value;
  return value.replace(/\{(\w+)\}/g, (match, name) =>
    params[name] === undefined || params[name] === null ? match : String(params[name]),
  );
}

export function actionLabel(action) {
  return (
    ACTION_LABELS[state.language]?.[action] || ACTION_LABELS.uz[action] || action
  );
}
